import { dirname } from "path";
import { fileURLToPath } from "url";
import { FlatCompat } from "@eslint/eslintrc";

// Flat config, because ESLint 9+ no longer reads .eslintrc.*. The repo had
// no config at all, so `next lint` dropped into its interactive setup and
// nothing was ever linted — tsc was the only gate. FlatCompat is still the
// supported way to consume eslint-config-next, which ships in the old format.

const compat = new FlatCompat({ baseDirectory: dirname(fileURLToPath(import.meta.url)) });

export default [
  {
    ignores: [
      "node_modules/**",
      ".next/**",
      "out/**",
      "build/**",
      "next-env.d.ts",
      // Generated by prisma generate; linting it is noise.
      "src/generated/**",
    ],
  },
  ...compat.extends("next/core-web-vitals", "next/typescript"),
  {
    rules: {
      // This codebase deliberately keeps unmodelled inbound fields as
      // `unknown` and narrows them by hand (see lib/leads-import.ts), so the
      // any-ban would fire on correct, defensive code. Warn, don't block.
      "@typescript-eslint/no-explicit-any": "warn",
      // Unused args prefixed with _ are intentional (destructuring a prop out
      // of a spread, e.g. `({ owner, ...l })` in the leads board).
      "@typescript-eslint/no-unused-vars": [
        "warn",
        { argsIgnorePattern: "^_", varsIgnorePattern: "^_", ignoreRestSiblings: true },
      ],
    },
  },
];
